/** Shared write transaction boundary for item mutations and queue lease/completion operations. */
import type { DatabaseSync } from "node:sqlite";

export function transaction<T>(db: DatabaseSync, fn: () => T): T {
  db.exec("BEGIN IMMEDIATE");
  try {
    const result = fn();
    db.exec("COMMIT");
    return result;
  } catch (error) {
    db.exec("ROLLBACK");
    throw error;
  }
}
